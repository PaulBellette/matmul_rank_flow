def reference_theta() -> torch.Tensor:
    U0 = torch.tensor(U_ROWS, dtype=torch.float64).T
    V0 = torch.tensor(V_ROWS, dtype=torch.float64).T
    W0 = torch.tensor(W_ROWS, dtype=torch.float64).T
    nu, nv, nw = U0.norm(dim=0), V0.norm(dim=0), W0.norm(dim=0)
    return pack(U0 / nu, V0 / nv, W0 / nw, nu * nv * nw)


if __name__ == "__main__":
    q = reference_theta()
    print(f"rank-23 tensor residual: {float(residual_vector(q, mm_tensor(3), 3, 23).norm()):.3e}")
